use sqlx::PgPool;

/// Membuat tabel yang dibutuhkan aplikasi jika belum tersedia.
/// Tabel existing tidak diubah oleh perintah CREATE TABLE IF NOT EXISTS.
pub async fn initialize(pool: &PgPool) -> Result<(), String> {
    sqlx::query(
        "CREATE TABLE IF NOT EXISTS barang (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nama TEXT NOT NULL,
            stok INTEGER NOT NULL,
            harga NUMERIC NOT NULL
        )",
    )
    .execute(pool)
    .await
    .map_err(|error| format!("Gagal menginisialisasi tabel `barang`: {error}"))?;

    sqlx::query(
        "CREATE TABLE IF NOT EXISTS users (
            username TEXT PRIMARY KEY,
            password TEXT NOT NULL
        )",
    )
    .execute(pool)
    .await
    .map_err(|error| format!("Gagal menginisialisasi tabel `users`: {error}"))?;

    Ok(())
}
